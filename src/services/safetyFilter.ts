/** NFKC正規化＋小文字化 */
function normalizeText(raw: string): string {
  return raw.normalize('NFKC').toLowerCase();
}

/** カタカナをひらがなへ統一 */
function toHiragana(text: string): string {
  return text.replace(/[\u30a1-\u30f6]/g, (ch) =>
    String.fromCharCode(ch.charCodeAt(0) - 0x60)
  );
}

/**
 * 伏せ字・スペース挟み・記号挟み・伸ばし棒連打などの回避表現を潰した比較用文字列を作る
 * 例: 「し・ね」「ク ソ」「きもーーい」「う ざ い」→「しね」「くそ」「きもい」「うざい」
 */
function toCompactHiragana(raw: string): string {
  const hira = toHiragana(normalizeText(raw));
  return hira
    .replace(/[\s\u3000・･.,。、!！?？_\-‐‑–—~〜～*＊×○◯●◎△▲□■/|\\「」『』()（）[\]［］]/g, '')
    .replace(/ー+/g, '');
}

