// 起動時に検索用の正規化済み配列を事前構築（高速スキャン用）
const PRECOMPILED_GROUPS = WORD_GROUPS.map((group) => ({
  category: group.category,
  entries: group.words.map((word) => ({
    raw: word,
    norm: normalizeText(word),
    hira: toHiragana(normalizeText(word)),
    compact: toCompactHiragana(word),
  })),
}));

/**
 * 単一のテキストに対して安心フィルターを実行する
 */
export function checkTextSafety(text: string): SafetyCheckResult {
  if (!text || text.trim().length === 0) {
    return { blocked: false };
  }

  // 1. 攻撃的・不快な絵文字チェック
  for (const emoji of BLOCKED_EMOJIS) {
    if (text.includes(emoji)) {
      return { blocked: true, matchedWord: emoji, category: 'emoji' };
    }
  }

  const norm = normalizeText(text);
  const hira = toHiragana(norm);
  const compact = toCompactHiragana(text);

  // 2. パターンルール（誤爆防止付き・伏せ字・英語スラング）
  for (const rule of PATTERN_RULES) {
    if (rule.pattern.test(text) || rule.pattern.test(norm) || rule.pattern.test(hira)) {
      return { blocked: true, matchedWord: rule.label, category: rule.category };
    }
  }

  // 3. 大量語彙辞書チェック（通常・ひらがな統一・記号/空白除去の3段階でスキャン）
  for (const group of PRECOMPILED_GROUPS) {
    for (const entry of group.entries) {
      if (
        norm.includes(entry.norm) ||
        hira.includes(entry.hira) ||
        (entry.compact.length >= 3 && compact.includes(entry.compact))
      ) {
        return { blocked: true, matchedWord: entry.raw, category: group.category };
      }
    }
  }

  return { blocked: false };
}

/**
 * 投稿（本文＋タグ）に対して安心フィルターを実行する
 */
export function checkPostSafety(post: {
  message?: string | null;
  tags?: readonly string[] | null;
}): SafetyCheckResult {
  if (post.message) {
    const res = checkTextSafety(post.message);
    if (res.blocked) return res;
  }

  if (post.tags && post.tags.length > 0) {
    for (const tag of post.tags) {
      const cleaned = tag.replace(/^#+/, '');
      const res = checkTextSafety(cleaned);
      if (res.blocked) return res;
    }
  }

  return { blocked: false };
}

